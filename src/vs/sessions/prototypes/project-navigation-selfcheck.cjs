// Run: node project-navigation-selfcheck.cjs (no dependencies).
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, 'project-navigation-prototype.html'), 'utf8');
const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)];
scripts.forEach(script => new vm.Script(script[1]));
const context = { structuredClone };
vm.createContext(context);
vm.runInContext(scripts[0][1], context);
let s = context.initial();
const act = action => { s = context.change(s, action); };
act({type:'chat', id:'worktree'});
assert.equal(s.view, 'worktree');
assert.equal(s.projects.worktree.active, 'chat:worktree');
assert.equal(s.open.length, 3);
act({type:'chat', id:'worktree'});
assert.equal(s.open.length, 3);
act({type:'requestClose', id:'worktree'});
act({type:'finishClose', choice:'backup'});
assert.equal(s.view, 'api');
assert.equal(s.chats.worktree.status, 'complete');
act({type:'view', id:'app'});
act({type:'signal', id:'approval'});
assert.equal(s.view, 'app');
assert.equal(s.chats.api.status, 'approval');
s.projects.app.dirty = true;
s.projects.app.originals['README.md'] = s.projects.app.files['README.md'];
s.projects.app.files['README.md'] = 'unsaved README';
s.projects.app.dirtyFiles['README.md'] = true;
act({type:'requestClose', id:'app'});
act({type:'finishClose', choice:'fail'});
assert.ok(s.open.includes('app'));
assert.equal(s.projects.app.files['README.md'], 'unsaved README');
act({type:'requestClose', id:'app'});
act({type:'finishClose', choice:'backup'});
act({type:'view', id:'app'});
assert.equal(s.projects.app.files['README.md'], 'unsaved README');
act({type:'requestClose', id:'app'});
act({type:'finishClose', choice:'discard'});
assert.notEqual(s.projects.app.files['README.md'], 'unsaved README');
act({type:'view', id:'app'});
act({type:'crowd'});
assert.equal(s.open.length, 10);
const order = s.open.join(',');
act({type:'restart'});
assert.equal(s.open.join(','), order);
assert.equal(s.view, 'app');
assert.equal(s.projects.api.terminal, false);
assert.equal(s.chats.app.status, 'interrupted');
for (const id of [...s.open]) { act({type:'requestClose', id}); act({type:'finishClose', choice:'backup'}); }
assert.equal(s.view, 'agents');
console.log('PASS: syntax, exact routing, duplicate reuse, close/restore, save failure, discard, attention, crowding, restart and final close.');
